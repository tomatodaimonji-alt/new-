const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const html=fs.readFileSync(process.argv[2]||'world-editor.html','utf8');
assert.match(html,/<dt>攻撃速度<\/dt>/,'weapon action timing must be labelled separately from movement');
const block=html.match(/\/\/ BEGIN ACTOR ATTRIBUTES\n([\s\S]*?)\/\/ END ACTOR ATTRIBUTES/);
assert(block,'missing shared actor attributes');
const t={};vm.runInNewContext(block[1]+'\nObject.assign(out,{poiStatStars,poiStatsGear,poiStatsWithGear,poiMovementFactor,poiLearnedDodge,poiRecordAttack,poiTuneWeapon});',{out:t});
assert.equal(t.poiStatStars(7),'★★★★★★★☆☆☆');
assert.equal(t.poiStatStars(11),'★★★★★★★★★★');
assert.equal(t.poiStatsGear('armorLeatherShoes').speed,1);
assert.equal(t.poiStatsWithGear({speed:5,intelligence:5},'equipIronSword',{feet:'armorLeatherShoes'}).speed,6);
assert(t.poiMovementFactor(7)>t.poiMovementFactor(5));
const actor={};
assert.equal(t.poiLearnedDodge(actor,'wood',10,1000,()=>0),false);
t.poiRecordAttack(actor,'wood',1000,35);
assert.equal(t.poiLearnedDodge(actor,'wood',10,1050,()=>0,35),false,'same multi-hit strike cannot teach its own second contact');
assert.equal(t.poiLearnedDodge(actor,'iron',10,2000,()=>0),false);
assert.equal(t.poiLearnedDodge(actor,'wood',1,2000,()=>.1),false);
assert.equal(t.poiLearnedDodge(actor,'wood',10,2000,()=>.1),true);
assert.equal(t.poiLearnedDodge(actor,'wood',10,2100,()=>0),false,'consecutive guaranteed dodges prevented');
assert.equal(t.poiLearnedDodge(actor,'wood',10,60000,()=>0),false);
for(let i=0;i<30;i++)t.poiRecordAttack(actor,'move'+i,60000,0);
assert(actor.learnedAttacks.size<=12);
const p={hit:200,pose:420,ready:470,speed:3};
const slow=t.poiTuneWeapon({...p,speedStars:3},6),fast=t.poiTuneWeapon({...p,speedStars:8},6);
assert(slow.hit>fast.hit&&slow.ready>fast.ready&&fast.hit<fast.pose&&fast.pose<=fast.ready);
const js=html.match(/<script>([\s\S]*?)<\/script>/g).map(s=>s.slice(8,-9));
for(const src of js)new vm.Script(src);
console.log('PASS actor stars, equipment, movement, bounded hit learning and shared attack timing');
