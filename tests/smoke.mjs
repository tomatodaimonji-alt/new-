import { chromium } from 'playwright';
import { createServer } from 'node:http';
import { readFileSync } from 'node:fs';
import { PNG } from 'pngjs';
const html=readFileSync('index.html','utf8');
const vertex=html.match(/const VERT='([^']+)'/)?.[1]||'';
const fragment=html.match(/const FRAG='([^']+)'/)?.[1]||'';
if(!vertex.includes('precision mediump float;')||!fragment.includes('precision mediump float;'))throw Error('Shader float precision must match');
if(vertex.includes('uniform vec3 uFog;'))throw Error('Unused uFog in vertex shader may cause link mismatch');
const server=createServer((req,res)=>{res.writeHead(200,{'content-type':'text/html; charset=utf-8'});res.end(html)});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const port=server.address().port;
let browser;
try{
 browser=await chromium.launch({headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push('console: '+m.text())});
 await page.goto('http://127.0.0.1:'+port,{waitUntil:'load'});
 await page.waitForTimeout(1500);
 console.log('WebGL supported?',await page.locator('canvas').evaluate(c=>!!c.getContext('webgl')));
 console.log('Before:',await page.locator('#pos').textContent());
 await page.getByText('森に入る',{exact:true}).click({timeout:10000});
 await page.waitForTimeout(1500);
 const hidden=await page.locator('#startLayer').evaluate(e=>getComputedStyle(e).display==='none');
 if(!hidden)throw Error('Intro did not disappear after tap');
 const programStatus=await page.locator('canvas').evaluate(canvas=>{const g=canvas.getContext('webgl');const p=g?.getParameter(g.CURRENT_PROGRAM);return {hasProgram:!!p,link:!!(p&&g.getProgramParameter(p,g.LINK_STATUS)),log:p?g.getProgramInfoLog(p):'No current program'};});
 console.log('WebGL program status:',programStatus);
 if(!programStatus.hasProgram||!programStatus.link)throw Error('3D WebGL shader program failed: '+programStatus.log);


 await page.screenshot({path:'smoke-test.png'});
 const cameraUp=await page.evaluate(()=>window.__forestCameraUpY);
 console.log('Actual 3D camera up-vector Y',cameraUp);
 if(!(cameraUp>0.25))throw Error('3D camera vertical orientation incorrect: '+cameraUp);
 const shot=PNG.sync.read(readFileSync('smoke-test.png'));
 const pixel=(x,y)=>{const i=(Math.floor(shot.height*y)*shot.width+Math.floor(shot.width*x))*4;return [shot.data[i],shot.data[i+1],shot.data[i+2]]};
 console.log('Scene pixels',pixel(.25,.23),pixel(.50,.48),pixel(.72,.65));
 if(!shot.width||!shot.height)throw Error('Empty WebGL screenshot');
 if((await page.locator('#startLayer').innerText()).includes('3Dの起動エラー'))throw Error('3D start error dialog');
 await page.keyboard.down('ArrowUp');await page.waitForTimeout(700);await page.keyboard.up('ArrowUp');
 const moved=await page.locator('#pos').textContent();
 console.log('After:',moved);
 if(moved.includes('X 0 / Z 0'))throw Error('Character did not move');
 const beforePad=await page.locator('#pos').textContent();
 const up=await page.locator('[data-dir="up"]').boundingBox();
 if(!up||up.width<50||up.height<50)throw Error('Portrait d-pad is too small or missing');
 await page.mouse.move(up.x+up.width/2,up.y+up.height/2);
 await page.mouse.down();
 await page.waitForTimeout(580);
 await page.mouse.up();
 const afterPad=await page.locator('#pos').textContent();
 console.log('Dpad test',beforePad,afterPad,'button dimensions',up.width,up.height);
 if(beforePad===afterPad)throw Error('Holding the on-screen D-pad did not move the character');
 await page.getByText('視点 1',{exact:true}).click();
 await page.getByText('歩く',{exact:true}).click();
 await page.screenshot({path:'smoke-test.png'});
 if(errors.length)throw Error('JavaScript error: '+errors.join(' ; '));
 console.log('SMOKE TEST PASSED');
}finally{await browser?.close();server.close()}
