import {chromium} from 'playwright';
import {createServer} from 'node:http';
import {readFileSync} from 'node:fs';
const html=readFileSync('index.html','utf8');
if(!html.includes('森の遺跡 3D')||!html.includes('getContext(\'webgl\''))throw Error('Wrong 3D game source');
const server=createServer((req,res)=>{res.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});res.end(html)});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
let browser;
try{
browser=await chromium.launch({headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',e=>{if(e.type()==='error')errors.push(e.text())});
await page.goto('http://127.0.0.1:'+server.address().port+'/?test=1',{waitUntil:'load'});
const initial=await page.evaluate(()=>window.__gameTest?.state());
if(!initial)throw Error('3D game failed to initialize: '+(await page.locator('#intro').innerText()));
if(!initial.glLink)throw Error('WebGL shader link failed');
if(initial.house.w!==9||initial.house.h!==8||initial.walls.length!==31)throw Error('One house or perimeter geometry wrong '+JSON.stringify(initial));
const wallSet=new Set(initial.walls);
for(const [x,z] of [[7,7],[15,7],[7,14],[15,14]])if(!wallSet.has(x+','+z))throw Error('Missing corner '+x+','+z);
if(wallSet.has('11,14'))throw Error('Door blocked');
await page.locator('#start').click();
await page.waitForTimeout(700);
if(await page.locator('#intro').isVisible())throw Error('Start button not working');
const sound=await page.evaluate(()=>window.__gameTest.audio());
if(!sound.created||sound.volume<80)throw Error('Audio did not initialize at usable volume');
await page.screenshot({path:'smoke-before.png'});
const start=await page.evaluate(()=>window.__gameTest.state());
const up=page.locator('[data-dir=up]'),bb=await up.boundingBox();
if(!bb||bb.width<55||bb.height<55)throw Error('Directional button is too small');
await page.mouse.move(bb.x+bb.width/2,bb.y+bb.height/2);await page.mouse.down();await page.waitForTimeout(1100);await page.mouse.up();
const moved=await page.evaluate(()=>window.__gameTest.state());
if(moved.z>start.z-2)throw Error('Grid movement did not advance multiple tiles '+JSON.stringify({start,moved}));
if(moved.face!==0)throw Error('Character facing did not change to north');
await page.screenshot({path:'smoke-after.png'});
await page.locator('#inspect').click();await page.locator('#camera').click();
await page.locator('#volume').fill('94');const changed=await page.evaluate(()=>window.__gameTest.audio());if(changed.volume!==94)throw Error('Volume UI not responsive');
await page.locator('#audioToggle').click();if((await page.evaluate(()=>window.__gameTest.audio())).music)throw Error('Music toggle failed');
if(errors.length)throw Error('Browser runtime errors: '+errors.join(' ; '));
console.log('PASS WebGL link, 24x24 map, single house, four solid corners, door, tile movement, direction, audio and volume');
}finally{await browser?.close();server.close()}
